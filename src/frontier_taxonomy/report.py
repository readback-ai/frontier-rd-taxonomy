# question-pack-<id>.md
# --------------------------------------------------------------------------
def question_pack(dataset: Dataset, branch_id: str) -> str:
    root = dataset.tasks[branch_id]
    out = [
        GENERATED,
        "",
        f"# Review questions: {root.name}",
        "",
        CANARY,
        "",
        "Questions a reviewer brings to a contribution, by task. They test understanding of the "
        "design, not recall of the code: someone who understands the contribution can answer "
        "without it open and without asking a model. Each question follows the comprehension "
        "audit's topical areas and tiers. Deep-tier areas (architecture and design, "
        "implementation behavior, process) need a thorough answer from at least one contributor. "
        "Familiarity-tier areas (key findings, analysis of results) need evidence of due "
        "consideration.",
        "",
    ]
    for task in dataset.branches[branch_id].tasks:
        question_set = dataset.question_sets.get(task.id)
        if not question_set:
            continue
        out += [
            f"## {task.name}",
            "",
            f"Contribution under review: {question_set.contribution}",
            "",
        ]
        for category in CATEGORY_ORDER:
            questions = [q for q in question_set.questions if q.category == category]
            if not questions:
                continue
            out += [f"### {CATEGORY_TITLE[category]}", ""]
            for question in questions:
                area = question.topical_area.replace("_", " ")
                out += [
                    f"**{question.question}**",
                    "",
                    f"`{question.id}` · {area} · {TIER_OF_AREA[question.topical_area]} tier",
                    "",
                    f"- A good answer shows: {question.good_answer_shows}",
                ]
                out += [f"- Red flag: {flag}" for flag in question.red_flags]
                if question.evidence_to_request:
                    out.append(f"- Ask to see: {question.evidence_to_request}")
                if question.risks:
                    out.append(f"- Aimed at: {', '.join(question.risks)}")
                out.append("")
    return "\n".join(out).rstrip() + "\n"


# --------------------------------------------------------------------------
# backtest.md
# --------------------------------------------------------------------------
def backtest_report(dataset: Dataset) -> str:
    out = [
        GENERATED,
        "",
        "# Backtest of review questions against incidents",
        "",
        CANARY,
        "",
        "For each incident, would a good-faith answer to the question have exposed the root "
        "cause before the incident? Verdicts are judgments recorded in each incident's file, "
        "made by a reviewer who did not write the questions. Where a question was written with "
        "knowledge of an incident, its verdict on that incident is in-sample: it shows the "
        "question is well aimed, not that it would have been asked. A verdict of would not "
        "surface marks a place where review is the wrong control.",
        "",
        "## By incident",
        "",
    ]
    rows = []
    for incident in sorted(dataset.incidents.values(), key=lambda i: i.id):
        verdicts = Counter(entry.verdict for entry in incident.backtest)
        rows.append(
            [
                f"`{incident.id}`",
                incident.title,
                incident.comprehension_failure,
                verdicts["would_surface"],
                verdicts["might_surface"],
                verdicts["would_not_surface"],
            ]
        )
    out.append(
        table(
            [
                "Incident",
                "Title",
                "Comprehension failure",
                "Would surface",
                "Might surface",
                "Would not",
            ],
            rows,
        )
    )
    tested = [i for i in dataset.incidents.values() if i.backtest]
    caught = [i for i in tested if any(e.verdict == "would_surface" for e in i.backtest)]
    if tested:
        out.append(
            f"{len(caught)} of {len(tested)} backtested incidents have at least one question "
            "judged to surface the root cause."
        )
        out.append("")

    out += ["## By question", ""]
    per_question: dict[str, Counter] = {}
    for incident in dataset.incidents.values():
        for entry in incident.backtest:
            per_question.setdefault(entry.question, Counter())[entry.verdict] += 1
    rows = [
        [
            f"`{question_id}`",
            dataset.questions[question_id].question if question_id in dataset.questions else "",
            counts["would_surface"],
            counts["might_surface"],
            counts["would_not_surface"],
        ]
        for question_id, counts in sorted(
            per_question.items(), key=lambda kv: (-kv[1]["would_surface"], kv[0])
        )
    ]
    out.append(table(["Question", "Text", "Would surface", "Might surface", "Would not"], rows))
    untested = sorted(set(dataset.questions) - set(per_question))
    out += ["## Questions no incident has tested", ""]
    out.append(", ".join(f"`{q}`" for q in untested) if untested else "_None._")
    out.append("")

    out += ["## Verdicts and reasons", ""]
    for incident in sorted(dataset.incidents.values(), key=lambda i: i.id):
        if not incident.backtest:
            continue
        out += [f"### {incident.title}", ""]
        for entry in incident.backtest:
            out.append(f"- `{entry.question}` {entry.verdict.replace('_', ' ')}: {entry.rationale}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def write_reports(paths: Paths, as_of: dt.date | None = None) -> list[Path]:
    dataset = load(paths)
    paths.reports.mkdir(parents=True, exist_ok=True)
    as_of = as_of or data_date(paths, dataset)
    written: list[Path] = []

    def write(name: str, text: str) -> None:
        path = paths.reports / name
        path.write_text(text, encoding="utf-8")
        written.append(path)

    write("coverage.md", coverage_report(paths, dataset, as_of))
    for branch_id, branch in sorted(dataset.branches.items()):
        slug = branch_id.removeprefix("T-")
        write(f"branch-{slug}.md", branch_report(dataset, branch_id))
        if any(t.id in dataset.question_sets for t in branch.tasks):
            write(f"question-pack-{slug}.md", question_pack(dataset, branch_id))
    write("backtest.md", backtest_report(dataset))
    written.append(write_gate_inputs(paths))
    return written
