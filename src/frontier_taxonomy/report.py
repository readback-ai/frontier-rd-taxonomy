# branch-<id>.md
# --------------------------------------------------------------------------
def branch_report(dataset: Dataset, branch_id: str) -> str:
    root = dataset.tasks[branch_id]
    out = [GENERATED, "", f"# {root.name}", "", root.description, ""]

    out += ["## Tasks and the attributes that drive risk", ""]
    rows = []
    for task in dataset.branches[branch_id].tasks:
        if task.id == branch_id:
            continue
        indent = "\u2003" * (dataset.depth(task.id) - 2)
        if dataset.is_leaf(task.id):
            rows.append(
                [
                    f"{indent}{task.name}",
                    ", ".join(task.output_roles),
                    task.verifiability or "",
                    task.feedback_latency or "",
                    task.failure_visibility or "",
                    task.reversibility or "",
                    (task.change_type or "").replace("_", " "),
                ]
            )
        else:
            rows.append([f"{indent}**{task.name}**", "", "", "", "", "", ""])
    out.append(
        table(
            [
                "Task",
                "Output role",
                "Verifiability",
                "Feedback",
                "Failure shows as",
                "Reversibility",
                "Change type",
            ],
            rows,
        )
    )

    out += ["## Estimates", ""]
    in_branch = {t.id for t in dataset.branches[branch_id].tasks}
    rows = [
        [
            dataset.tasks[e.task].name,
            e.quantity.replace("_", " "),
            e.scope,
            e.as_of,
            format_value(e),
            e.basis,
            e.confidence,
            ", ".join(e.evidence),
        ]
        for e in sorted(dataset.estimates.values(), key=lambda e: (e.task, e.quantity, e.as_of))
        if e.task in in_branch
    ]
    out.append(
        table(
            ["Task", "Quantity", "Scope", "As of", "Value", "Basis", "Confidence", "Evidence"],
            rows,
        )
    )

    out += ["## Risks", ""]
    risks = sorted(
        (r for r in dataset.risks.values() if in_branch.intersection(r.tasks)),
        key=lambda r: r.id,
    )
    for risk in risks:
        out += [
            f"### {risk.title}",
            "",
            f"`{risk.id}` · severity {risk.severity} · {risk.status.replace('_', ' ')} · "
            f"harm path: {risk.harm_path.replace('_', ' ')}",
            "",
            f"- **Tasks:** {', '.join(dataset.tasks[t].name for t in risk.tasks)}",
            f"- **Failure mode:** {risk.failure_mode}",
            f"- **Mechanisms:** {', '.join(m.replace('_', ' ') for m in risk.mechanisms)}",
            f"- **What automation changes:** {risk.automation_effect}",
            f"- **Would a design review catch it:** {risk.review_catchable}. "
            f"{risk.review_rationale}",
        ]
        if risk.evidence:
            out.append(f"- **Evidence:** {', '.join(risk.evidence)}")
        if risk.incidents:
            out.append(f"- **Incidents:** {', '.join(risk.incidents)}")
        out.append("")

    out += ["## Incidents", ""]
    incidents = sorted(
        (i for i in dataset.incidents.values() if in_branch.intersection(i.tasks)),
        key=lambda i: i.occurred,
    )
    for incident in incidents:
        out += [
            f"### {incident.title}",
            "",
            f"`{incident.id}` · {incident.org} · {incident.occurred} · "
            f"{'frontier' if incident.frontier else 'analog'}",
            "",
            incident.summary,
            "",
            f"- **Root cause:** {incident.root_cause}",
            f"- **Found by:** {incident.detected_by}"
            + (f" ({incident.detection_latency})" if incident.detection_latency else ""),
            f"- **Automation involved:** {incident.automation_involved}",
            f"- **Comprehension failure:** {incident.comprehension_failure}. "
            f"{incident.comprehension_note}",
            f"- **Evidence:** {', '.join(incident.evidence)}",
            "",
        ]
    if not incidents:
        out += ["_None._", ""]
    return "\n".join(out).rstrip() + "\n"


