"""Generated reports. Everything under ``reports/`` comes from here; nothing is hand-edited.

Reports carry no clock time. Their date is the data date: the latest day any quote was
verified. Running the generator twice on the same records gives the same files, so CI can
check that the committed reports match the records.
"""

from __future__ import annotations

import datetime as dt
from collections import Counter
from pathlib import Path

from .config import Paths
from .locks import read_lock
from .pacing import write_gate_inputs
from .schema import (
    CANARY,
    TIER_OF_AREA,
    CategoryValue,
    Estimate,
    LevelsValue,
    LevelValue,
    PointValue,
    RangeValue,
    Task,
)
from .store import Dataset, load
from .validate import evidence_status, stale_estimates

GENERATED = "<!-- Generated by `taxo report`. Do not edit by hand. -->"
CATEGORY_ORDER = ("what", "why", "failure", "dependency", "side_effects", "provenance")
CATEGORY_TITLE = {
    "what": "What",
    "why": "Why",
    "failure": "Failure",
    "dependency": "Dependencies",
    "side_effects": "Side effects",
    "provenance": "Provenance",
}


def data_date(paths: Paths, dataset: Dataset) -> dt.date | None:
    """The latest day a quote was verified, or None if nothing has been."""
    dates = [
        stamp.verified
        for source_id in dataset.sources
        for stamp in read_lock(paths, source_id).quotes.values()
    ]
    return dt.date.fromisoformat(max(dates)) if dates else None


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def table(headers: list[str], rows: list[list[object]]) -> str:
    if not rows:
        return "_None._\n"
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def _number(value: float) -> str:
    if value == 0:
        return "0"
    if abs(value) < 1:
        return f"{value:.3g}"
    return f"{value:,.3g}" if abs(value) < 1000 else f"{value:,.0f}"


def format_value(estimate: Estimate) -> str:
    value = estimate.value
    if isinstance(value, LevelValue):
        return value.level
    if isinstance(value, LevelsValue):
        parts = [f"{level} {share:.0%}" for level, share in sorted(value.shares.items())]
        return ", ".join(parts)
    if isinstance(value, CategoryValue):
        return value.value.replace("_", " ")
    share = estimate.quantity.endswith("_share") or estimate.quantity == "human_review_coverage"
    show = (lambda v: f"{v:.0%}" if v >= 0.1 else f"{v:.1%}") if share else _number
    if isinstance(value, PointValue):
        return show(value.value)
    if isinstance(value, RangeValue):
        return f"{show(value.central)} ({show(value.low)} to {show(value.high)})"
    raise TypeError(type(value))


def _leaves(dataset: Dataset, branch_id: str) -> list[Task]:
    return [t for t in dataset.branches[branch_id].tasks if dataset.is_leaf(t.id)]


def _latest_by_scope(dataset: Dataset, task_id: str, quantity: str) -> list[Estimate]:
    """The most recent estimate of a quantity for a task, one per scope, ordered by scope."""
    latest: dict[str, Estimate] = {}
    for estimate in dataset.estimates.values():
        if estimate.task != task_id or estimate.quantity != quantity:
            continue
        current = latest.get(estimate.scope)
        if current is None or (estimate.as_of, estimate.id) > (current.as_of, current.id):
            latest[estimate.scope] = estimate
    return [latest[scope] for scope in sorted(latest)]


def _by_scope_cell(estimates: list[Estimate]) -> str:
    """One table cell naming each scope's value and basis: estimates never merge across scopes."""
    return "; ".join(f"{e.scope}: {format_value(e)} [{e.basis}]" for e in estimates)


def _evidence_by_task(dataset: Dataset) -> Counter:
    counts: Counter = Counter()
    for item in dataset.evidence.values():
        for task_id in item.tasks:
            counts[task_id] += 1
    return counts


