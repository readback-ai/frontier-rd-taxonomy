# coverage.md
# --------------------------------------------------------------------------
def coverage_report(paths: Paths, dataset: Dataset, as_of: dt.date | None) -> str:
    status = evidence_status(paths, dataset)
    out = [GENERATED, "", "# Coverage", ""]
    out.append(f"Data date: {as_of.isoformat() if as_of else 'no verified evidence yet'}.")
    out.append("")

    out += ["## Sources by type", ""]
    by_type = Counter(source.type for source in dataset.sources.values())
    items_by_type: Counter = Counter()
    for evidence_id in dataset.evidence:
        items_by_type[dataset.sources[dataset.evidence_source[evidence_id]].type] += 1
    out.append(
        table(
            ["Type", "Sources", "Evidence items"],
            [[t.replace("_", " "), n, items_by_type[t]] for t, n in by_type.most_common()],
        )
    )

    out += ["## Evidence by grade", ""]
    grades = sorted({item.grade for item in dataset.evidence.values()})
    rows = []
    for grade in grades:
        ids = [i for i, item in dataset.evidence.items() if item.grade == grade]
        states = Counter(status[i] for i in ids)
        rows.append([grade, len(ids), states["verified"], states["excused"], states["unverified"]])
    out.append(table(["Grade", "Items", "Verified", "Excused", "Unverified"], rows))
    total = len(dataset.evidence)
    verified = sum(1 for s in status.values() if s == "verified")
    out.append(f"{verified} of {total} quotes are verified against a snapshot.")
    out.append("")

    out += ["## Estimates by basis", ""]
    basis = Counter(e.basis for e in dataset.estimates.values())
    n = len(dataset.estimates)
    out.append(
        table(
            ["Basis", "Estimates", "Share"],
            [[b, basis[b], f"{basis[b] / n:.0%}"] for b in ("evidence", "mixed", "judgment") if n],
        )
    )
    if n:
        out.append(
            f"{basis['judgment']} of {n} estimates ({basis['judgment'] / n:.0%}) rest on judgment "
            "alone." + (" They are priors, not findings." if basis["judgment"] else "")
        )
        out.append("")

    out += ["## Branches", ""]
    evidence_counts = _evidence_by_task(dataset)
    tasks_with_risk = Counter(t for r in dataset.risks.values() for t in r.tasks)
    for branch_id, branch in sorted(dataset.branches.items()):
        root = dataset.tasks[branch_id]
        out += [f"### {root.name} (`{branch_id}`, {branch.status})", ""]
        rows = []
        for task in _leaves(dataset, branch_id):
            automation = _latest_by_scope(dataset, task.id, "automation_level")
            oversight = _latest_by_scope(dataset, task.id, "oversight_mode")
            rows.append(
                [
                    f"`{task.id}`",
                    task.name,
                    _by_scope_cell(automation),
                    _by_scope_cell(oversight),
                    evidence_counts[task.id],
                    tasks_with_risk[task.id],
                    len(dataset.question_sets[task.id].questions)
                    if task.id in dataset.question_sets
                    else 0,
                ]
            )
        out.append(
            table(
                ["Task", "Name", "Automation", "Oversight", "Evidence", "Risks", "Questions"], rows
            )
        )

    out += ["## Risks", ""]
    by_status = Counter(r.status for r in dataset.risks.values())
    by_catch = Counter(r.review_catchable for r in dataset.risks.values())
    out.append(
        table(
            ["Status", "Risks"],
            [[s.replace("_", " "), by_status[s]] for s in sorted(by_status)],
        )
    )
    out.append(
        table(
            ["Would a design review catch it", "Risks"],
            [[c, by_catch[c]] for c in ("yes", "partly", "no") if by_catch[c]],
        )
    )

    out += ["## Stale estimates", ""]
    stale = stale_estimates(dataset, as_of) if as_of else []
    out.append(
        table(["Estimate", "As of", "Stale after"], [[e.id, e.as_of, e.stale_after] for e in stale])
    )

    out += ["## Evidence without a verified quote", ""]
    rows = [
        [evidence_id, state, dataset.evidence[evidence_id].unverified_reason or ""]
        for evidence_id, state in sorted(status.items())
        if state != "verified"
    ]
    out.append(table(["Evidence", "State", "Reason"], rows))
    return "\n".join(out).rstrip() + "\n"


