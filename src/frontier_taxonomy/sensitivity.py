"""Run the readback-ops pacing model on the bottom-up gate inputs and rank the inputs.

The pacing model is not part of this repository. ``taxo sensitivity --model-dir PATH`` imports
it from a checkout of readback-ops (research/pacing-takeoff-model) and needs scipy, which the
``pacing`` extra installs. Everything else here takes a ``runner``: a function from the
pacing-model block to a dictionary of results, so the ranking logic is tested without the model.

What is varied is each recorded input, one at a time from its 10th to its 90th percentile, and
then all of them together. What is reported is how far the model's result moves. An input that
moves the result most is the one worth measuring first.
"""

