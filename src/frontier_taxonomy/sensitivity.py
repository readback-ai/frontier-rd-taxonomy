Runner = Callable[[dict], dict[str, float]]
GENERATED = "<!-- Generated by `taxo sensitivity`. Do not edit by hand. -->"
POLICIES = (
    "No pacing",
    "Human sign-off, no comprehension standard",
    "Comprehension audits, light",
    "Comprehension audits, central",
    "Comprehension audits, strict",
)
CENTRAL = "Comprehension audits, central"
SHORT = {COUNT: "count", HOURS: "hours", ELASTICITY: "elasticity", SHARE: "progress share"}


@dataclass(frozen=True)
class Row:
    """One input moved from its low to its high value, everything else held central."""

    task: str
    change_type: str
    quantity: str
    low: float
    central: float
    high: float
    basis: str
    at_low: float
    at_high: float
    log_scale: bool = False

    @property
    def swing(self) -> float:
        """How far the result moves: a difference, or a ratio's log on a log scale."""
        if self.log_scale:
            if min(self.at_low, self.at_high) <= 0:
                return math.inf
            return abs(math.log(self.at_high / self.at_low))
        return abs(self.at_high - self.at_low)


def one_at_a_time(
    dataset: Dataset, runner: Runner, metric: str, scope: str = FRONTIER, log_scale: bool = False
) -> list[Row]:
    """Each recorded gate input at its low and its high value, ranked by the swing in ``metric``."""
    rows = []
    for key, item in sorted(gate_values(dataset, scope).items()):
        low, central, high = item.triple
        at = [
            runner(pacing_block(gate_inputs(dataset, scope, {key: end}, spread=False)))[metric]
            for end in (low, high)
        ]
        rows.append(Row(*key, low, central, high, item.basis, at[0], at[1], log_scale))
    rows.sort(key=lambda r: (-r.swing, r.task, r.change_type, r.quantity))
    return rows


def joint_draws(
    dataset: Dataset, runner: Runner, draws: int = 150, scope: str = FRONTIER
) -> list[dict[str, float]]:
    """The result with every input drawn at once from its interval, ``draws`` times."""
    values = gate_values(dataset, scope)
    samples = {key: _draws(item, draws) for key, item in values.items()}
    return [
        runner(
            pacing_block(
                gate_inputs(dataset, scope, {k: float(samples[k][n]) for k in values}, spread=False)
            )
        )
        for n in range(draws)
    ]


def weighted_elasticity(block: dict) -> float:
    """Elasticity of deployed changes to AI labor, weighted by each type's share of progress."""
    types = block["change_types"].values()
    total = sum(t["progress_weight"] for t in types)
    return sum(t["progress_weight"] * t["elasticity"] for t in types) / total


# --------------------------------------------------------------------------
# The readback-ops model
# --------------------------------------------------------------------------
class PacingModel:
    """Model A of the readback-ops pacing model, with its gate replaced on request."""

    def __init__(self, model_dir: Path):
        self.model_dir = Path(model_dir).resolve()
        if not (self.model_dir / "pacing_model.py").exists():
            raise FileNotFoundError(f"no pacing_model.py in {self.model_dir}")
        sys.path.insert(0, str(self.model_dir))
        import pacing_model  # noqa: PLC0415  (imported from the checkout named at run time)

        self.pm = pacing_model
        self.calibration = pacing_model.load_calibration()
        self.model, _ = pacing_model.build_a(self.calibration)
        self.unpaced = self._summary(self._policies(self.calibration)["No pacing"])

    def version(self) -> str:
        def git(*args: str) -> str:
            done = subprocess.run(
                ["git", "-C", str(self.model_dir), *args],
                capture_output=True,
                text=True,
                check=False,
            )
            return done.stdout.strip() or "unknown"

        return (
            f"{git('rev-parse', '--abbrev-ref', 'HEAD')} at {git('rev-parse', '--short', 'HEAD')}"
        )

    def with_block(self, block: dict | None) -> dict:
        """The model's calibration with the gate's change types replaced by ``block``."""
        calibration = copy.deepcopy(self.calibration)
        if block:
            gate = calibration["comprehension_gate"]
            gate["change_types"] = copy.deepcopy(block["change_types"])
            if "monitor_changes" in block:
                gate["monitor_changes"] = dict(block["monitor_changes"])
        return calibration

    def _policies(self, calibration: dict) -> dict:
        return {p.name: p for p in self.pm.standard_policies(calibration)}

    def _summary(self, policy) -> dict[str, float]:
        run = self.model.simulate(policy)
        summary = self.pm.summarize_a(self.model, run)
        return {
            "t_sar": summary["t_sar"],
            "pace_2027.5": summary["pace_2027.5"],
            "pace_2028": summary["pace_2028.0"],
            "pace_2029": self.pm.value_at(run["t"], run["pace"], 2029.0),
        }

    def run(self, block: dict | None, policy: str = CENTRAL) -> dict[str, float]:
        """Results under one policy. ``block=None`` keeps the model's own gate assumptions."""
        result = self._summary(self._policies(self.with_block(block))[policy])
        result["sar_delay_months"] = (result["t_sar"] - self.unpaced["t_sar"]) * 12.0
        return result


