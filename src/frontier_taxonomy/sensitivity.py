def _n(value: float, digits: int = 2) -> str:
    if value != value:
        return "off scale"
    return f"{value:.{digits}g}" if abs(value) < 100 else f"{value:,.0f}"


def _pace(value: float) -> str:
    return "off scale" if value != value else f"{value:.1f}x"


def _table(headers: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def _percentiles(values: list[float]) -> tuple[float, float, float]:
    finite = [v for v in values if v == v]
    if not finite:
        return (math.nan,) * 3
    return tuple(float(x) for x in np.percentile(finite, [10, 50, 90]))


def sensitivity_report(
    dataset: Dataset, model: PacingModel, draws: int, as_of: dt.date | None
) -> str:
    document = gate_document(dataset)
    block = document["pacing_model"]
    top_down = model.calibration["comprehension_gate"]
    out = [GENERATED, "", "# The pacing model on bottom-up gate inputs", ""]
    out += [
        f"Data date: {as_of.isoformat() if as_of else 'no verified evidence yet'}. "
        f"Gate inputs fingerprint: `{digest(document)}`. "
        f"Pacing model: readback-ops `{model.version()}`, Model A only.",
        "",
        "Every bottom-up input below is a judgment prior. This report shows what the pacing "
        "model does with them and which of them moves its result most. It is a guide to what "
        "to measure, not a forecast.",
        "",
    ]

    out += ["## Inputs: the model's assumption and the bottom-up prior", ""]
    table = document["change_types"]
    rows = []
    for change_type, name in PACING_NAMES.items():
        if name not in block["change_types"]:
            continue
        ours, theirs = table[change_type], top_down["change_types"].get(name, {})

        def cell(quantity: str, ours=ours) -> str:
            c = ours[quantity]
            return f"{_n(c['central'])} ({_n(c['low'])} to {_n(c['high'])})"

        rows.append(
            [
                name.replace("_", " "),
                theirs.get("per_researcher_year", ""),
                cell(COUNT),
                theirs.get("hours_to_understand", ""),
                cell(HOURS),
                theirs.get("elasticity", ""),
                cell(ELASTICITY),
                theirs.get("progress_weight", ""),
                _n(block["change_types"][name]["progress_weight"]),
            ]
        )
    monitor = block.get("monitor_changes", {})
    rows.append(
        [
            "required overhead (" + ", ".join(block["folded_into_monitor_changes"]) + ")",
            top_down["monitor_changes"]["per_researcher_year"],
            _n(monitor.get("per_researcher_year", math.nan)),
            top_down["monitor_changes"]["hours_to_understand"],
            _n(monitor.get("hours_to_understand", math.nan)),
            "",
            "",
            "",
            "",
        ]
    )
    out.append(
        _table(
            [
                "Change type",
                "Count: model",
                "Count: bottom-up",
                "Hours: model",
                "Hours: bottom-up",
                "Elasticity: model",
                "Elasticity: bottom-up",
                "Weight: model",
                "Weight: bottom-up",
            ],
            rows,
        )
    )
    totals = document["totals"]
    gate = model.pm.gate_from_calibration(model.calibration)
    count, share = (
        totals["changes_per_researcher_year"],
        totals["comprehension_load_share_of_researcher_year"],
    )
    out += [
        f"Deployed changes per researcher-year: the model assumes {_n(gate.changes_at_reference)}. "
        f"Bottom-up gives {_n(count['at_central_values'])} at central values, and a median of "
        f"{_n(count['p50'])} ({_n(count['p10'])} to {_n(count['p90'])}) when the priors vary.",
        "",
        "Share of a researcher-year needed to understand all of it: the model assumes "
        f"{gate.hours_at_reference / gate.hours_per_year:.0%}. Bottom-up gives "
        f"{share['at_central_values']:.0%} at central values, and a median of {share['p50']:.0%} "
        f"({share['p10']:.0%} to {share['p90']:.0%}) when the priors vary.",
        "",
        "The central values understate the typical case: wide, right-skewed priors add up to "
        "more than their medians. The run at central values below is therefore the low-load "
        "end, and the joint draws further down are the fairer summary.",
        "",
    ]

    out += ["## Results under each mechanism", ""]
    rows = []
    for policy in POLICIES:
        theirs, ours = model.run(None, policy), model.run(block, policy)
        rows.append(
            [
                policy,
                f"{theirs['sar_delay_months']:+.0f} mo",
                f"{ours['sar_delay_months']:+.0f} mo",
                _pace(theirs["pace_2028"]),
                _pace(ours["pace_2028"]),
                _pace(theirs["pace_2029"]),
                _pace(ours["pace_2029"]),
            ]
        )
    out.append(
        _table(
            [
                "Mechanism",
                "SAR delay: model",
                "SAR delay: bottom-up",
                "Pace Jan 2028: model",
                "Pace Jan 2028: bottom-up",
                "Pace Jan 2029: model",
                "Pace Jan 2029: bottom-up",
            ],
            rows,
        )
    )
    out += [
        '"Model" uses the pacing model\'s own gate assumptions. "Bottom-up" replaces them with '
        "the central values above. SAR is the capability level the pacing model calls a "
        "superhuman AI researcher. Pace is the rate of progress relative to the 2024 rate.",
        "",
    ]

    out += [f"## Across the priors ({draws} joint draws, central audits)", ""]
    results = joint_draws(
        dataset, lambda b: {**model.run(b, CENTRAL), "elasticity": weighted_elasticity(b)}, draws
    )
    rows = []
    for label, key, show in (
        ("Pace in Jan 2028", "pace_2028", _pace),
        ("Pace in Jan 2029", "pace_2029", _pace),
        ("Delay to SAR", "sar_delay_months", lambda v: f"{v:+.1f} mo"),
    ):
        p10, p50, p90 = _percentiles([r[key] for r in results])
        rows.append([label, show(p10), show(p50), show(p90)])
    out.append(_table(["Result", "10th percentile", "Median", "90th percentile"], rows))
    fast = [r for r in results if r["pace_2029"] != r["pace_2029"] or r["pace_2029"] > 10]
    held = [r for r in results if r not in fast]
    if fast and held:
        among_fast = np.median([r["elasticity"] for r in fast])
        among_held = np.median([r["elasticity"] for r in held])
        out += [
            f"In {len(fast)} of {draws} draws the pace in January 2029 is above 10x or off scale, "
            "so on these priors central audits do not reliably hold the pace down. What separates "
            "those draws is how fast deployed changes grow with AI labor: their progress-weighted "
            f"elasticity has a median of {among_fast:.2f}, against {among_held:.2f} in the draws "
            "where the pace is held.",
            "",
        ]
    elif fast:
        out += [f"In all {draws} draws the pace in January 2029 is above 10x or off scale.", ""]
    else:
        out += [f"In all {draws} draws the pace in January 2029 stays at or below 10x.", ""]

    out += ["## Which input to measure first", ""]
    ranked = one_at_a_time(dataset, lambda b: model.run(b, CENTRAL), "pace_2028", log_scale=True)
    rows = []
    for rank, row in enumerate(ranked, start=1):
        rows.append(
            [
                rank,
                f"`{row.task}`",
                row.change_type.replace("_", " "),
                SHORT[row.quantity],
                f"{_n(row.central)} ({_n(row.low)} to {_n(row.high)})",
                row.basis,
                _pace(row.at_low),
                _pace(row.at_high),
                f"{math.exp(row.swing):.2f}x" if math.isfinite(row.swing) else "off scale",
            ]
        )
    out.append(
        _table(
            [
                "Rank",
                "Task",
                "Change type",
                "Input",
                "Prior",
                "Basis",
                "Pace Jan 2028 at low",
                "at high",
                "Swing",
            ],
            rows,
        )
    )
    out += [
        "Each input is moved from its 10th to its 90th percentile with the others at their "
        "central values, under central audits. Swing is the ratio between the two results. "
        "Required-overhead inputs act only through the hours they take off the top: the model "
        "has no elasticity for them, so their growth with AI labor is not tested here.",
        "",
    ]
    return "\n".join(out).rstrip() + "\n"


def write_sensitivity(paths: Paths, model_dir: Path, draws: int = 150) -> Path:
    from .report import data_date  # noqa: PLC0415  (report imports pacing; avoid a cycle)

    dataset = load(paths)
    text = sensitivity_report(dataset, PacingModel(model_dir), draws, data_date(paths, dataset))
    paths.reports.mkdir(parents=True, exist_ok=True)
    out = paths.reports / "sensitivity.md"
    out.write_text(text, encoding="utf-8")
    return out


def recorded_fingerprint(paths: Paths) -> str | None:
    """The gate-inputs fingerprint a written sensitivity report was run on, if there is one."""
    path = paths.reports / "sensitivity.md"
    if not path.exists():
        return None
    marker = "Gate inputs fingerprint: `"
    text = path.read_text(encoding="utf-8")
    start = text.find(marker)
    return text[start + len(marker) :].split("`", 1)[0] if start >= 0 else None
